"""
compiler/targets/dbt.py
========================
DbtEmitter — SPEC_40-A (SPEC_41-A updated)

Turns a governed entity + metrics + optional view into dbt + MetricFlow artifacts.

SPEC_40-A file paths (MetricFlow semantic output):
  models/staging/stg_<entity_snake>.sql         — identity / typed staging model
  models/marts/<entity_snake>__<metric_snake>.sql — one model per metric (ID + value)
  models/marts/<entity_snake>_wide.sql           — LEFT JOIN all metrics (fold invariant)
  models/marts/<entity_snake>_view.sql           — authored view rewritten to ref(wide)
  models/marts/_<entity_snake>.yml               — MetricFlow semantic_models + metrics

SPEC_41-A file paths (gold-standard MESA dbt export — model_zoo_bq shape):
  models/mesa/raw_layer/raw_<entity>.sql         — verbatim authored SQL (hashed ID)
  models/mesa/metric_layer/<Entity>_Metrics/<metric>.sql — 1 metric per file
  models/mesa/metric_layer/<entity>_metrics.sql  — assembler CTE fold
  models/mesa/wide_layer/wide_<entity>.sql       — dialect-aware composite
  models/mesa/view_layer/v_<entity>_*.sql        — BI view over wide
  models/mesa/schema.yml                         — governance projection (SPEC_41-B)

Design guarantees
-----------------
* emit() is PURE and DETERMINISTIC — no git I/O, no network, no DB.
  All side-effectful git writing lives in integrations/definitions/git_writer.py.
* Fold invariant (SPEC_38): the wide model and MetricFlow semantic YAML ALWAYS fold
  ALL metrics. A single-metric redeploy still emits the full wide + full YAML so no
  measures are dropped from the deployed MetricFlow definition.
* The semantic YAML (_<entity>.yml) is the whole point.  A warehouse table alone is
  NOT a MetricFlow metric.  The semantic_models + metrics blocks make the metrics
  queryable via `mf query --metrics <name>`.  Do NOT remove them.
* Non-trivial aggregations (windowed, ratio, complex expressions) emit a
  ``# MESANTIC: manual review — non-trivial aggregation`` comment rather than
  silently mapping to `sum`.  Silent mis-aggregation is a compliance defect.
* CodeConnection is stored but only used for context comments.
  Actual git I/O happens in GitWriter outside this class.

MetricFlow agg-type mapping
-----------------------------
  MESA expression pattern        MetricFlow agg type
  ─────────────────────────────────────────────────────
  SUM(...)                       sum
  COUNT(...)                     count
  COUNT(DISTINCT ...)            count_distinct
  AVG(...)                       average
  MAX(...)                       max
  MIN(...)                       min
  (none of the above)            *comment-flagged* — engineer must review

Wire-label preservation
-----------------------
  Artifact.object_type uses MESA-specific labels for dbt artifacts:
    "dbt_staging"    → staging model
    "dbt_metric"     → one metric model
    "dbt_wide"       → wide model (fold)
    "dbt_view"       → authored view (rewritten)
    "dbt_semantic"   → MetricFlow semantic YAML
  These do NOT overlap with the MESA warehouse tier labels
  ("raw" / "metric" / "widetable" / "view") — they must never be confused.
"""

