"""
report.py — render a ConformanceReport as ``docs/WAREHOUSE_BEHAVIOR.md``.

SPEC_103 Slice 8 item 3. The output is the honest version of the "identical
across every warehouse" claim: each row is VERIFIED (with the date and the
warehouse version) or FALSIFIED (with what actually happened). Slices 2, 4 and 7
read from this file, so a row that turns out false changes a slice — that's the
point of running it.

The renderer is deliberately plain markdown with no timestamps beyond the run
date, so a regenerated file diffs cleanly and a reviewer can see exactly which
rows changed.
"""

from __future__ import annotations

from mesa_core.conformance.harness import ConformanceReport

_HEADER = """\
# Warehouse behavior — measured, not documented

Generated by `mesa_core.conformance` (SPEC_103 Slice 8). Do not hand-edit — re-run
the harness instead.

Every row below is one of two things:

- **VERIFIED** — the warehouse was run and behaved as the spec's DOCUMENTED row
  claims. The date and warehouse version are recorded so the row is reproducible.
- **FALSIFIED** — it behaved differently. The `Actual` column says what happened,
  and the slice that depends on the row needs revisiting.

**SKIPPED** is not a pass. A check that couldn't run is a gap in the evidence, and
it's counted separately so "0 falsified" is never read as "all good".

Slice 8a (DuckDB) runs in CI and is free. It is a regression suite for mesa-core's
own compiler, **not** a stand-in for cloud behavior — DuckDB's `concat` ignores
NULL and `/` returns a double, which is not what SQL Server does. The cloud rows
wait for Slice 8b, which costs about $1/hr per warehouse and needs approval per run.
"""


def render_markdown(reports: list[ConformanceReport]) -> str:
    """Render one or more warehouse reports into a single markdown document."""
    parts: list[str] = [_HEADER]

    for report in reports:
        parts.append(_render_one(report))

    parts.append(_render_gaps(reports))
    return "\n".join(parts).rstrip() + "\n"


def _render_one(report: ConformanceReport) -> str:
    lines: list[str] = [
        "",
        f"## {report.warehouse} {report.version}",
        "",
        f"Run {report.run_at}. {report.summary()}.",
        "",
        "| Case | Check | Status | Expected | Actual |",
        "|---|---|---|---|---|",
    ]
    for result in report.results:
        lines.append(
            f"| `{result.case}` | {result.check} | **{result.status.value}** "
            f"| {_cell(result.expected)} | {_cell(result.actual)} |"
        )

    notes = [r for r in report.results if r.note]
    if notes:
        lines.extend(["", "### What each row means", ""])
        for result in notes:
            lines.append(f"- **`{result.case}`** — {result.note}")

    return "\n".join(lines)


def _render_gaps(reports: list[ConformanceReport]) -> str:
    """The closing section: what is still DOCUMENTED rather than VERIFIED.

    This is the part that keeps the file honest. A reader who skims the tables
    and sees all-VERIFIED needs to know which warehouses were never run.
    """
    ran = {r.warehouse for r in reports}
    not_run = [
        name
        for name in ("Snowflake", "BigQuery", "Redshift", "Synapse", "AzureSQLDatabase")
        if name not in ran
    ]

    lines = ["", "## Still DOCUMENTED, not VERIFIED", ""]
    if not not_run:
        lines.append("Every supported warehouse has been run. No DOCUMENTED rows remain.")
        return "\n".join(lines)

    lines.append(
        "These warehouses have not been run by the harness. Every claim about them "
        "in SPEC_103 is still DOCUMENTED — do not build a rule on one until Slice 8b "
        "confirms it:"
    )
    lines.append("")
    for name in not_run:
        lines.append(f"- **{name}** — not run")

    lines.extend(
        [
            "",
            "The rows that specifically wait on these runs:",
            "",
            "- **NULL in `CONCAT`** (Slice 2 item 4) — SQL Server vs Snowflake.",
            "- **The four cross-warehouse identity claims** (Slice 2 item 5) — hex case, "
            "input bytes, Snowflake `SHA2` vs `SHA2_BINARY`, Redshift UDF wording.",
            "- **`AVG` over an integer column** (Slice 4 item 4) — SQL Server returns an "
            "int before the cast, so a `FLOAT` cast can't recover the lost decimals.",
            "- **Integer division** (Slice 7 item 1) — Redshift and SQL Server truncate.",
            "- **`MIN`/`MAX` on `BIT`** (Slice 6 item 1) — T-SQL `BIT` is the named example.",
        ]
    )
    return "\n".join(lines)


def _cell(text: str) -> str:
    """Escape a value for a markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ")
